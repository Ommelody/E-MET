  <h1 class="doc-title">ข้อกำหนดและขอบเขตของงาน (Terms of Reference: TOR)</h1>
  <p class="doc-sub">โครงการจัดหาระบบบริหารจัดการการเบิกจ่ายวัสดุและพัสดุคงคลัง<br>(THAMC e-Material)</p>

  <h2>๑. ความเป็นมาและหลักการเหตุผล</h2>
  <p>ด้วยหน่วยงานมีความจำเป็นต้องบริหารจัดการวัสดุและพัสดุคงคลังเป็นจำนวนมาก การดำเนินงานด้วยระบบเอกสารและการบันทึกด้วยมือในปัจจุบันก่อให้เกิดความล่าช้า ความคลาดเคลื่อนของข้อมูลคงคลัง และความยากลำบากในการตรวจสอบย้อนหลัง จึงมีความประสงค์จะจัดหาระบบสารสนเทศเพื่อการบริหารจัดการการเบิกจ่ายวัสดุและพัสดุคงคลังแบบครบวงจร ที่สามารถควบคุมกระบวนการตั้งแต่การร้องขอเบิก การอนุมัติตามลำดับชั้น การจ่ายพัสดุ การรับพัสดุเข้าคลัง ตลอดจนการจัดทำรายงานและเอกสารประกอบได้อย่างถูกต้อง โปร่งใส และตรวจสอบได้</p>

  <h2>๒. วัตถุประสงค์</h2>
  <ol class="thai">
    <li><span class="n">๒.๑</span> เพื่อให้มีระบบบริหารจัดการการเบิกจ่ายวัสดุและพัสดุคงคลังในรูปแบบอิเล็กทรอนิกส์ ทดแทนการทำงานด้วยเอกสาร</li>
    <li><span class="n">๒.๒</span> เพื่อควบคุมกระบวนการอนุมัติการเบิกจ่ายตามลำดับชั้นของผู้มีอำนาจ</li>
    <li><span class="n">๒.๓</span> เพื่อให้ข้อมูลปริมาณคงคลังเป็นปัจจุบันและถูกต้อง ลดความคลาดเคลื่อนของสต๊อก</li>
    <li><span class="n">๒.๔</span> เพื่อให้สามารถจัดทำรายงานและตรวจสอบความเคลื่อนไหวของพัสดุย้อนหลังได้</li>
    <li><span class="n">๒.๕</span> เพื่อเพิ่มความโปร่งใสและประสิทธิภาพในการบริหารพัสดุของหน่วยงาน</li>
  </ol>

  <h2>๓. คุณสมบัติของผู้เสนอราคา</h2>
  <ol class="thai">
    <li><span class="n">๓.๑</span> เป็นนิติบุคคลหรือบุคคลธรรมดาที่ประกอบกิจการพัฒนาระบบสารสนเทศหรือซอฟต์แวร์</li>
    <li><span class="n">๓.๒</span> มีผลงานหรือประสบการณ์ในการพัฒนาระบบสารสนเทศในลักษณะเดียวกัน</li>
    <li><span class="n">๓.๓</span> ไม่เป็นผู้ถูกระบุชื่อไว้ในบัญชีรายชื่อผู้ทิ้งงานของทางราชการ</li>
    <li><span class="n">๓.๔</span> มีความสามารถในการให้บริการดูแลบำรุงรักษาและสนับสนุนหลังการติดตั้ง</li>
  </ol>

  <h2>๔. ขอบเขตของงาน (Scope of Work)</h2>
  <p class="noindent">ผู้รับจ้างต้องส่งมอบระบบที่มีความสามารถอย่างน้อย ดังนี้</p>

  <h3>๔.๑ ระบบบริหารจัดการผู้ใช้งานและสิทธิ์การเข้าถึง</h3>
  <ul>
    <li>รองรับการเข้าสู่ระบบด้วยชื่อผู้ใช้และรหัสผ่านที่มีการเข้ารหัสตามมาตรฐาน (bcrypt)</li>
    <li>กำหนดสิทธิ์การใช้งานตามบทบาท (Role) อย่างน้อย ๔ ระดับ ได้แก่ ผู้ดูแลระบบ (Admin) ผู้จัดการ (Manager) เจ้าหน้าที่พัสดุ (Staff) และผู้ใช้ทั่วไป (User)</li>
    <li>ผู้ดูแลระบบสามารถเพิ่ม แก้ไข ลบผู้ใช้ และจัดการหน่วยงาน/แผนกได้</li>
  </ul>

  <h3>๔.๒ ระบบจัดการคลังพัสดุ (Inventory)</h3>
  <ul>
    <li>บันทึก แก้ไข ลบ และค้นหารายการวัสดุ พร้อมจัดเก็บรูปภาพประกอบ</li>
    <li>กำหนดจุดสั่งซื้อขั้นต่ำ และจำนวนเบิกสูงสุดต่อครั้งของวัสดุแต่ละรายการ</li>
    <li>แสดงการแจ้งเตือนวัสดุที่มีปริมาณต่ำกว่าจุดสั่งซื้อ</li>
  </ul>

  <h3>๔.๓ ระบบการเบิกจ่ายและการอนุมัติ</h3>
  <ul>
    <li>สร้างใบเบิกวัสดุพร้อมระบุวัตถุประสงค์และรายการที่ต้องการ</li>
    <li>กระบวนการอนุมัติตามลำดับชั้น (หัวหน้างาน → เจ้าหน้าที่พัสดุ) พร้อมสามารถปรับยอดอนุมัติและยอดจ่ายจริงได้</li>
    <li>รองรับการอนุมัติและจ่ายพัสดุแบบเป็นชุด (Batch) และรายรายการ</li>
    <li>รองรับกรณีจ่ายพัสดุบางส่วน (ค้างจ่าย) และการติดตามจ่ายของค้าง</li>
  </ul>

  <h3>๔.๔ ระบบรับพัสดุเข้าคลัง (Goods Receipt)</h3>
  <ul>
    <li>บันทึกการรับพัสดุเข้าคลังด้วยตนเอง และนำเข้าจากไฟล์ (Excel)</li>
    <li>ปรับปรุงปริมาณคงคลังและราคาต่อหน่วยโดยอัตโนมัติ</li>
  </ul>

  <h3>๔.๕ ระบบตรวจสอบความเคลื่อนไหวและรายงาน</h3>
  <ul>
    <li>ตรวจสอบความเคลื่อนไหวของพัสดุรายตัว (รับเข้า/จ่ายออก) พร้อมวันที่และปลายทาง</li>
    <li>รายงานอย่างน้อย ๗ ประเภท พร้อมตัวกรองตามช่วงเวลา หน่วยงาน และหมวดหมู่</li>
    <li>ส่งออกรายงานในรูปแบบไฟล์ Excel ได้</li>
    <li>จัดทำเอกสารใบเบิกและใบจ่ายพัสดุที่สามารถพิมพ์และบันทึกเป็นไฟล์ PDF ได้</li>
  </ul>

