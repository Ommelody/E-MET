  <h2>๗. การรับประกันและการบำรุงรักษา</h2>
  <ol class="thai">
    <li><span class="n">๗.๑</span> ผู้รับจ้างต้องรับประกันความชำรุดบกพร่องของระบบเป็นระยะเวลาไม่น้อยกว่า ๑ ปี นับจากวันตรวจรับ</li>
    <li><span class="n">๗.๒</span> ให้บริการแก้ไขข้อผิดพลาดของระบบ (Bug Fix) และสนับสนุนการใช้งานตลอดระยะเวลารับประกัน</li>
    <li><span class="n">๗.๓</span> กำหนดระยะเวลาการกู้คืนระบบ (RTO) ไม่เกิน ๒ ชั่วโมง และจุดกู้คืนข้อมูล (RPO) ไม่เกิน ๒๔ ชั่วโมง</li>
  </ol>

  <h2>๘. การฝึกอบรมและเอกสารประกอบ</h2>
  <ul>
    <li>จัดการฝึกอบรมการใช้งานระบบแก่เจ้าหน้าที่ผู้เกี่ยวข้อง</li>
    <li>ส่งมอบคู่มือการใช้งานระบบ (User Manual) และคู่มือผู้ดูแลระบบ</li>
  </ul>

