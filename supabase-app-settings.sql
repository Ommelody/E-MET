## 3. แผนรับมือระบบล่ม (Disaster Recovery)

### กรณีที่ 1: Render เซิร์ฟเวอร์ล่ม/ดาวน์
- **ผลกระทบ:** เข้าเว็บไม่ได้ ข้อมูลใน Supabase ยังปลอดภัย (คนละระบบ)
- **แก้ไข:** Render Dashboard → Manual Deploy ใหม่ หรือรอระบบ auto-restart (Render จะ restart service ที่ crash ให้อัตโนมัติ)
- **เวลากู้คืนโดยประมาณ:** 2–10 นาที

### กรณีที่ 2: Supabase ล่ม (ฝั่งผู้ให้บริการ)
- **ผลกระทบ:** ใช้งานไม่ได้ทั้งระบบ (ล็อกอิน/ข้อมูลเข้าถึงไม่ได้)
- **แก้ไข:** รอผู้ให้บริการแก้ (เช็กสถานะที่ status.supabase.com) — ไม่มีอะไรทำได้ฝั่งเรานอกจากรอ
- **ป้องกันความเสี่ยงนี้ไม่ได้ 100%** แต่เกิดน้อยมาก (uptime Supabase ปกติ >99.9%)

### กรณีที่ 3: ข้อมูลถูกลบ/แก้ผิดพลาดโดยผู้ใช้
- **แก้ไข:** กู้คืนจาก Supabase backup (ถ้าเป็น Pro) หรือจากไฟล์ backup ที่สำรองเอง (หัวข้อ 4)
- **ป้องกันล่วงหน้า:** จำกัดสิทธิ์ลบข้อมูล (ตอนนี้เฉพาะ Admin ลบได้อยู่แล้ว) + เพิ่ม confirm dialog (มีอยู่แล้วในระบบ)

### กรณีที่ 4: โดนโจมตี/แฮ็ก
- **ป้องกัน:** service key ไม่เปิดเผย (env var), รหัสผ่านเป็น bcrypt แล้ว, RLS เปิดใช้งาน
- **ถ้าเกิดขึ้น:** เปลี่ยน SUPABASE_SERVICE_KEY ทันที (Supabase Dashboard → rotate key) + บังคับผู้ใช้ทุกคนเปลี่ยนรหัสผ่าน

