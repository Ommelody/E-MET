## 2. แผนสำรองฐานข้อมูล (สำคัญที่สุด)

### ระดับ Supabase (อัตโนมัติ)
- **แพลน Free:** **ไม่มี** backup อัตโนมัติให้ — ความเสี่ยงสูงสุด ถ้าใช้จริงกับองค์กรไม่ควรอยู่แพลนนี้
- **แพลน Pro (~$25/เดือน):** Supabase สำรองให้อัตโนมัติ **ทุกวัน เก็บย้อนหลัง 7 วัน** (Point-in-Time Recovery ได้ถ้าซื้อ add-on เพิ่ม)
- **คำแนะนำ:** สำหรับองค์กร 400–500 คน **ต้องอัปเป็น Pro** เพื่อให้มี backup อัตโนมัติขั้นต่ำ

### ระดับสำรองเสริมเอง (แนะนำเพิ่ม แม้อยู่ Pro แล้ว)
อย่าพึ่ง backup ของผู้ให้บริการเพียงอย่างเดียว — ควรมีสำเนาอิสระที่คุณควบคุมเอง:
- รันสคริปต์ export ข้อมูลเป็นไฟล์ (มีให้ในโปรเจกต์แล้ว ดูหัวข้อ 4) **สัปดาห์ละครั้งเป็นอย่างน้อย**
- เก็บไฟล์ backup ไว้คนละที่กับ Supabase (เช่น Google Drive ขององค์กร, S3, หรือฮาร์ดดิสก์สำรอง)
- ตั้งกฎ **3-2-1**: สำเนา 3 ชุด, เก็บ 2 สื่อต่างกัน, อย่างน้อย 1 ชุดอยู่คนละสถานที่จริง

