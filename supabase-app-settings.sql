# แผนสำรองข้อมูล และรับมือระบบล่ม (Backup & Disaster Recovery)
THAMC e-Material — สำหรับผู้ดูแลระบบ

> เอกสารนี้ตอบ 2 คำถาม: **(1)** ข้อมูลหายจะกู้คืนยังไง **(2)** ระบบล่มจะกลับมาใช้งานได้เร็วแค่ไหน

---

## 1. สิ่งที่ต้องสำรอง (Backup Scope)

| ส่วน | เก็บอยู่ที่ | ความเสี่ยงถ้าหาย |
|---|---|---|
| ฐานข้อมูล (users, inventory, requisitions, transaction_logs ฯลฯ) | Supabase Postgres | **สูงสุด** — ข้อมูลธุรกิจทั้งหมด |
| ไฟล์เอกสาร (ใบเบิก/ใบจ่าย HTML, รูปวัสดุ) | Supabase Storage (`pdfs`, `catalog-images`) | กลาง — สร้างใหม่จาก DB ได้บางส่วน |
| โค้ดระบบ (frontend+backend) | GitHub repo | ต่ำ — มีสำเนาในเครื่องคุณ + Git history |
| ค่า config (env vars: SUPABASE_URL, SERVICE_KEY) | Render Dashboard | กลาง — ถ้าหายต้องตั้งใหม่ (จด/เก็บใน password manager) |

