## 6. วิธีสำรองข้อมูลด้วยตัวเอง

ใช้สคริปต์ `scripts/backup.mjs` ที่แนบมาในโปรเจกต์นี้ — ดึงข้อมูลทุกตารางจาก Supabase ผ่าน service key แล้วบันทึกเป็นไฟล์ JSON ลงเครื่อง

```bash
cd thamc-v2
node scripts/backup.mjs
```

จะได้โฟลเดอร์ `backups/YYYY-MM-DD/` ที่มีไฟล์ JSON ของทุกตาราง — เก็บโฟลเดอร์นี้ไว้ที่ปลอดภัย (อัปโหลดขึ้น Google Drive องค์กร หรือที่เก็บสำรองอื่น)

> รันตอนไหนก็ได้ที่เครื่องมี Node.js และมีไฟล์ `.env` (SUPABASE_URL, SUPABASE_SERVICE_KEY) ครบ — แนะนำตั้งเตือนปฏิทินให้รันทุกสัปดาห์
