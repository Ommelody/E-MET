## 5. Checklist สำหรับผู้ดูแลระบบ

- [ ] อัป Supabase เป็นแพลน Pro ก่อนใช้งานจริงกับองค์กร (มี auto-backup)
- [ ] รันสคริปต์ export ข้อมูลเอง **ทุกสัปดาห์** เก็บไว้คนละที่ (ดูหัวข้อ 6)
- [ ] เก็บค่า `SUPABASE_URL` / `SUPABASE_SERVICE_KEY` ไว้ใน password manager (ไม่ใช่แชต/โน้ตธรรมดา)
- [ ] ทดสอบ "กู้คืนจริง" อย่างน้อยปีละ 1 ครั้ง (import ไฟล์ backup กลับเข้า Supabase project ทดสอบ) — backup ที่ไม่เคยทดสอบกู้คืน ถือว่าไม่มี backup
- [ ] จดขั้นตอนติดต่อ Support ของ Render และ Supabase ไว้ล่วงหน้า (ลิงก์ + เวลาตอบกลับโดยประมาณ)

