## 4. เป้าหมายเวลากู้คืน (RTO/RPO) — ควรระบุให้ลูกค้าเห็นชัด

| ตัวชี้วัด | นิยาม | ค่าที่ระบบนี้ทำได้ (แพลน Pro) |
|---|---|---|
| **RTO** (Recovery Time Objective) — กู้คืนใช้เวลาเท่าไหร่ | ระบบกลับมาใช้ได้ภายใน | ~30 นาที – 2 ชั่วโมง (ขึ้นกับต้อง restore DB หรือไม่) |
| **RPO** (Recovery Point Objective) — ข้อมูลหายได้มากสุดกี่ชั่วโมง | ข้อมูลล่าสุดที่กู้คืนได้ ย้อนไปไม่เกิน | 24 ชั่วโมง (backup รายวันของ Supabase Pro) |

> ถ้าลูกค้าต้องการ RPO ต่ำกว่านี้ (เช่น 1 ชั่วโมง) ต้องซื้อ Point-in-Time Recovery add-on ของ Supabase เพิ่ม

